assert.match(modal, /w-8 h-8 rounded-lg/)

assert.match(modal, /draggable=\{reorderingId === null\}/)
assert.match(modal, /cursor-grab active:cursor-grabbing/)
assert.match(modal, /categoryManagement\.dragAria/)
