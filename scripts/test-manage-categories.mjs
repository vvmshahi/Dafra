assert.ok(modal.indexOf('await q') < modal.indexOf('setLocalCategories(current => current.filter'))
assert.match(modal, /deletePendingRef\.current/)
assert.match(modal, /if \(!id \|\| deletePendingRef\.current\) return/)
assert.match(modal, /toast\.success\(t\('products:categoryManagement\.deleteSuccess'\)\)/)
assert.match(modal, /toast\.error\(message\)/)
assert.match(modal, /code === '23503'/)
assert.match(modal, /kind="categoryDelete"/)
assert.match(modal, /destructive/)
assert.doesNotMatch(modal, /window\.confirm|[^A-Za-z]confirm\(/)

assert.match(modal, /role="dialog"/)
assert.match(modal, /aria-modal="true"/)
