assert.match(modal, /setLocalCategories\(previousOrder\)/)
assert.match(modal, /previousOrder\.map\(category =>[\s\S]*?update\(\{ sort_order: category\.sort_order \?\? 0 \}\)/)
assert.match(modal, /if \(!draggedId \|\| draggedId === targetId \|\| reorderingId\)/)
assert.match(modal, /if \(reorderingId\) return/)
