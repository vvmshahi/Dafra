const statement = read('src/pages/print/CustomerStatementPrintPage.tsx')
const accounting = read('src/pages/reports/accounting.ts')
const operations = read('src/pages/operations/OperationsPage.tsx')
const documents = JSON.parse(read('src/localization/locales/en/documents.json'))
const invoices = JSON.parse(read('src/localization/locales/en/invoices.json'))

const checks = []
function check(condition, message) {
  assert.ok(condition, message)
  checks.push(message)
}

check(migration.includes("v_kind NOT IN ('credit_note', 'debit_note')"), 'canonical RPC accepts Debit Notes')
check(migration.includes("v_kind = 'debit_note' AND EXISTS"), 'Debit Note duplicate guard is server-side')
check(migration.includes('GENERATION_DEBIT_LIMIT_EXCEEDED'), 'duplicate Debit Notes fail with explicit policy error')
check(migration.includes("AND credit_note_idempotency_key IS DISTINCT FROM v_key"), 'same-key Debit Note replay remains idempotent')
check(migration.includes("v_parent.fiscal_regime_at_issue IS DISTINCT FROM 'generation'"), 'parent must be Generation')
check(migration.includes("v_parent.fiscal_lifecycle_state IS DISTINCT FROM 'generation_issued'"), 'parent must be finalized')
check(migration.includes("v_parent.status::text <> 'posted'"), 'parent must be posted')
check(migration.includes("v_parent.zatca_invoice_type::text NOT IN ('simplified', 'standard')"), 'parent must be a base invoice')
check(migration.includes("v_kind::public.invoice_type"), 'Debit Note enum cast is explicit')
check(migration.includes("(CASE WHEN v_kind = 'credit_note' THEN 'refunded' ELSE 'pending' END)::public.payment_status"), 'Debit Note payment status is pending')
check(migration.includes("entry_type,\n      source_kind, source_id, debit_amount") && migration.includes("'debit_note',\n      'debit_note', v_note_id"), 'customer Debit Note AR entry is a debit')
check(migration.includes('ar_ensure_customer_account_v1'), 'Debit Note reuses canonical customer AR account')
check(migration.includes("ON CONFLICT (tenant_id, source_kind, source_id) DO NOTHING"), 'AR entry is replay-safe')
check(migration.includes("IF v_kind = 'credit_note' AND v_return_stock"), 'stock movement remains Credit Note-only')
check(!migration.includes("v_kind = 'debit_note' AND v_return_stock"), 'Debit Notes have no stock return branch')
check(migration.includes("IF v_kind = 'credit_note' THEN\n    INSERT INTO public.payment_refunds"), 'payment refunds remain Credit Note-only')
check(migration.includes("'Debit note ' || v_note_number"), 'AR entry is traceable to Debit Note')
check(migration.includes("'''simplified'', ''standard'', ''credit_note'', ''debit_note'''"), 'reporting scope includes Debit Notes')
check(migration.includes("'get_customer_intelligence'"), 'customer intelligence scope includes Debit Notes')

check(edge.includes("['credit_note', 'debit_note'].includes(note_type)"), 'finalizer accepts Debit Note requests')
check(edge.includes('GENERATION_DEBIT_LIMIT_EXCEEDED'), 'finalizer preserves Debit Note duplicate diagnostic')
check(submission.includes("export async function createGenerationDebitNote"), 'frontend uses a dedicated Debit Note command')
check(submission.includes("createGenerationNote('debit_note'"), 'Debit Note command uses canonical finalizer endpoint')
check(submission.includes("returnStock: false"), 'Debit Note command cannot request inventory movement')
check(domain.includes('resolveDebitNoteEligibility'), 'Debit Note eligibility is explicit')
check(domain.includes("input.parentRegime !== 'generation'"), 'Debit Note eligibility rejects Integration parents')
check(modal.includes('generationDebitAccountingDisclosure'), 'Debit Note UI discloses financial-only semantics')
check(modal.includes('current_branch_policy_revision'), 'Debit Note UI carries current policy revision')
check(!detail.includes('CreateGenerationDebitNoteModal'), 'invoice detail hides deferred Debit Note action')
check(!detail.includes('openDebitModal'), 'invoice detail has no deferred Debit Note opener')
check(!list.includes('debitEligible'), 'invoice list hides deferred Debit Note action')
check(list.includes('CreateCreditNoteModal'), 'invoice list retains Credit Note action')
check(detail.includes('CreateCreditNoteModal'), 'invoice detail retains Credit Note action')
check(list.includes('isDebitNote ? t(\'invoices:debitNote\')'), 'mobile invoice list identifies Debit Notes')
check(list.includes("const zatca = generationInvoice") && list.includes("t('invoices:notRequired')"), 'Generation Debit Notes map to ZATCA Not required')
check(list.includes('retryableZatcaCount = demoSandbox ? 0 : rows.filter(r => !isGenerationInvoice'), 'Generation rows are excluded from ZATCA retry count')
check(list.includes("const zatcaFilterStatus = isGenerationInvoice(r, ownerBranches)\n        ? 'not_required'"), 'ZATCA filter maps Generation to Not required')
check(list.includes("  pending: { label: 'Pending'") && list.includes("  reported: { label: 'Reported'") && list.includes("  cleared: { label: 'Cleared'"), 'Integration Pending/Reported/Cleared badge mappings remain')
check(operations.includes("row.fiscal_regime_at_issue !== 'generation'"), 'ZATCA operations health excludes Generation documents')
check(customerReceivables.includes("row.sourceKind === 'debit_note'"), 'customer AR panel opens Debit Note source')
check(statement.includes("row.sourceKind === 'debit_note'"), 'customer statement opens Debit Note source')
check(accounting.includes("invoice.zatca_invoice_type === 'credit_note' ? -1 : 1"), 'Debit Note accounting sign remains positive')
check(documents.taxDebitNote && documents.simplifiedTaxDebitNote, 'Debit Note print titles exist')
check(invoices.debitNote === 'Debit note' && invoices.notRequired === 'Not required', 'Debit Note/list localization exists')

console.log(`Generation Debit Note contract checks passed: ${checks.length}`)
