import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8')
const migration = read('supabase/migrations/20260824001400_generation_debit_notes_accounting.sql')
const edge = read('supabase/functions/fiscal-finalize-generation/index.ts')
const submission = read('src/lib/zatca/submission.ts')
const domain = read('src/lib/fiscal/domain.ts')
const modal = read('src/pages/invoices/CreateGenerationDebitNoteModal.tsx')
