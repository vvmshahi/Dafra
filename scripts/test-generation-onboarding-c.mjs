import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'

const read = async path => readFile(new URL(`../${path}`, import.meta.url), 'utf8')
const migration = await read('supabase/migrations/20260824000500_generation_onboarding_c.sql')
const ownerEdge = await read('supabase/functions/create-owner-account/index.ts')
const clients = await read('src/pages/super-admin/ClientsPage.tsx')
const adminLocale = await read('src/localization/locales/en/admin.json')
const zatca = await read('src/pages/settings/ZatcaTab.tsx')
const readiness = await read('src/lib/fiscal/readiness.ts')
const invoices = await read('src/pages/invoices/InvoicesPage.tsx')
const protectedSubmitter = await read('supabase/functions/zatca-submit/index.ts')
let count = 0
const check = (condition, message) => { assert.ok(condition, message); count += 1 }

check(migration.includes('tenant_fiscal_onboarding_intents'), 'tenant fiscal intent is durable')
check(migration.includes("requested_regime IN ('generation', 'integration')"), 'intent is constrained to fiscal regimes')
check(migration.includes('capture_owner_fiscal_onboarding_intent'), 'owner provisioning captures intent server-side')
check(migration.includes('apply_fiscal_onboarding_intent_to_branch'), 'branch mode derives from tenant intent')
check(migration.includes("NEW.fiscal_activation_state := 'generation_active'"), 'Generation activation is server-derived')
check(migration.includes('prevent_client_fiscal_policy_spoof'), 'client fiscal policy spoofing is blocked')
check(migration.includes('FISCAL_POLICY_SERVER_AUTHORITATIVE'), 'spoofing fails closed')
check(migration.includes('get_generation_readiness_v1'), 'canonical Generation readiness RPC exists')
check(migration.includes('generationMissingFields'), 'readiness returns missing fields')
check(migration.includes('integrationReadiness'), 'Integration readiness is separate')
check(migration.includes('begin_integration_setup_v1'), 'Integration preparation RPC exists')
check(migration.includes("v_role <> 'owner'"), 'Integration preparation is owner-only')
check(migration.includes("fiscal_activation_state = 'integration_setup'"), 'preparation does not cut over regime')
check(ownerEdge.includes("fiscal_regime: body.fiscal_regime === 'generation' ? 'generation' : 'integration'"), 'edge normalizes fiscal intent')
check(ownerEdge.includes('safePayload.fiscal_regime'), 'fiscal intent is fingerprinted')
check(adminLocale.includes('"generationMode": "Generation Phase"'), 'business-facing Generation choice exists')
check(adminLocale.includes('"integrationMode": "Integration Phase"'), 'business-facing Integration choice exists')
check(clients.includes("fiscal_intent: fiscalRegime === 'generation' ? 'generation' : 'integration_setup'"), 'UI submits canonical fiscal intent to server')
check(!clients.includes('zatca_phase: 2'), 'super-admin choice is not a technical phase selector')
check(readiness.includes('get_generation_readiness_v1'), 'browser uses canonical readiness RPC')
check(readiness.includes('begin_integration_setup_v1'), 'browser uses canonical preparation RPC')
check(zatca.includes("branch.fiscal_regime !== 'generation'"), 'Generation branches skip ZATCA status calls')
check(zatca.includes('GenerationReadinessPanel'), 'ZATCA page has Generation readiness UX')
check(zatca.includes("generation.active"), 'ZATCA page shows Generation active')
check(zatca.includes("t('generation.connect')"), 'owner gets Integration CTA')
check(zatca.includes('profile?.role === \'owner\''), 'CTA is owner gated')
check(invoices.includes('fiscal_regime_at_issue'), 'invoice list reads issue regime')
check(invoices.includes('generation_issued'), 'Generation finality is recognized')
check(invoices.includes('crossRegimeNoteNotAllowed'), 'cross-regime notes fail safely')
check(invoices.includes("r.fiscalRegimeAtIssue !== 'generation'"), 'Generation documents are excluded from retry count')
check(protectedSubmitter === await read('supabase/functions/zatca-submit/index.ts'), 'protected submitter remains readable and unchanged')

console.log(`Generation onboarding C assertions passed: ${count}`)
