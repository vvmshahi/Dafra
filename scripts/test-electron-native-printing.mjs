import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8')
const main = read('electron/main.cjs')
const printer = read('electron/printer.cjs')
const preload = read('electron/preload.cjs')
const bridge = read('src/lib/electron.ts')
const labels = read('src/lib/barcodes/labelPrint.ts')
const native = read('src/lib/barcodes/nativePrint.ts')
const settings = read('src/pages/settings/PrinterTab.tsx')

assert.match(main, /barcodePrinterName: null/)
assert.match(main, /barcodeCopies: 1/)
assert.match(main, /documentHtml\.length > 2_000_000/)
assert.match(main, /data-kubri-barcode-print="v1"/)
assert.match(main, /pageWidthMm/)
assert.match(main, /maxCopies: 500/)
assert.match(main, /assertSelectedPrinterAvailable\(sender, validated\.printerName\)/)
assert.match(main, /margins: \{ marginType: 'custom', top: 0, bottom: 0, left: 0, right: 0 \}/)
assert.match(printer, /getPrintersAsync\(\)\.then/)
assert.match(printer, /displayName/)
assert.match(preload, /ipcRenderer\.invoke\('print-barcode'/)
assert.match(bridge, /printBarcode: \(request: BarcodePrintRequest\)/)
assert.match(bridge, /barcodeCopies: 1/)
assert.match(labels, /data-kubri-page-width-mm/)
assert.match(labels, /PRINTER TEST \/ اختبار الطابعة/)
assert.match(native, /parsed\.querySelectorAll\('script'\)/)
assert.match(native, /browserBarcodePrintAdapter\.print\(documentHtml\)/)
assert.match(settings, /\['barcode'/)
assert.match(settings, /barcodePrinterName/)
assert.match(settings, /barcodeCopies/)

console.log('Electron native printing contract passed (receipt, A4, barcode, local settings, and browser fallback).')
