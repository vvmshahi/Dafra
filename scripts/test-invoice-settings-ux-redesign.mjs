import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import ts from 'typescript'

const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8')
const page = read('src/pages/branch/InvoiceSettingsPage.tsx')
const settings = read('src/lib/invoices/presentationSettings.ts')
const receiptHelper = read('src/lib/receiptPrint.ts')
const pos = read('src/pages/pos/POSPage.tsx')
const receiptPage = read('src/pages/print/ReceiptPrintPage.tsx')
const invoiceDetail = read('src/pages/invoices/InvoiceDetailPage.tsx')
const totals = read('src/lib/invoices/visibleTotals.ts')
const thermal = read('src/components/print/ThermalReceipt.tsx')
const a4 = read('src/components/print/A4Document.tsx')
const architecture = read('docs/invoice-presentation-architecture.md')
const persistenceContract = read('scripts/sql/invoice-settings-ux/06_stabilize_v1_settings_contract.sql')
const persistenceVerification = read('scripts/sql/invoice-settings-ux/07_verify_v1_settings_contract.sql')

const js = ts.transpileModule(settings, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText
const { normalizeInvoiceSettings, toCanonicalInvoicePresentationSettings, serializeInvoicePresentationSettingsForSave } = await import(`data:text/javascript,${encodeURIComponent(js)}`)
const branch = { name: 'Branch', business_name: 'Company', invoice_language: 'en', print_mode: 'thermal', show_logo: true, show_footer: true, show_cash_change: true }
const legacy = normalizeInvoiceSettings(undefined, branch)
const envelope = normalizeInvoiceSettings({ presentation_settings: { ...legacy.presentation, after_sale_action: 'a4', identity: { ...legacy.presentation.identity, show_company_name: false }, thermal: { ...legacy.presentation.thermal, width: '58mm', density: 'compact', qr_size: 'large', qr_alignment: 'right' } }, invoice_language: 'ar', print_mode: 'pdf' }, branch)
assert.equal(legacy.presentation.thermal.width, '80mm')
assert.equal(envelope.invoiceLanguage, 'ar')
assert.equal(envelope.printMode, 'pdf')
assert.equal(envelope.presentation.thermal.width, '58mm')
assert.equal(envelope.presentation.thermal.density, 'compact')
assert.equal(envelope.presentation.thermal.qr_size, 'large')
assert.equal(legacy.afterSaleAction, 'receipt')
assert.equal(envelope.afterSaleAction, 'a4')
assert.equal(normalizeInvoiceSettings({ presentation_settings: { after_sale_action: 'thermal' } }, branch).afterSaleAction, 'receipt')
assert.equal(normalizeInvoiceSettings({ presentation_settings: { after_sale_action: 'both' } }, branch).afterSaleAction, 'both')
assert.equal(envelope.presentation.thermal.qr_alignment, 'center')
const canonical = toCanonicalInvoicePresentationSettings({ presentation: envelope.presentation, invoiceLanguage: 'ar', afterSaleAction: 'both' }, branch.name)
const roundTrip = normalizeInvoiceSettings({ presentation_settings: canonical }, branch)
const preserved = normalizeInvoiceSettings({ presentation_settings: { ...canonical, future_extension: { sentinel: true } } }, branch)
const preservedCanonical = toCanonicalInvoicePresentationSettings(preserved, branch.name)
const saveFixture = {
  ...envelope.presentation,
  logo: { ...envelope.presentation.logo, asset_path: 'branch-id/logo.png' },
  footer: { ...envelope.presentation.footer, footer_note: 'Thank you' },
}
const failingDraft = {
  ...envelope,
  presentation: saveFixture,
  invoiceLanguage: 'en',
  afterSaleAction: 'both',
  printMode: 'pdf',
  preservedSettings: { legalSeller: { registeredName: 'must not be persisted' }, previewOnly: true },
}
const saveContract = serializeInvoicePresentationSettingsForSave(failingDraft, branch.name)
assert.deepEqual(Object.keys(saveContract).sort(), ['a4', 'after_sale_action', 'branding', 'contact', 'footer', 'language', 'thermal'])
assert.deepEqual(Object.keys(saveContract.branding).sort(), ['custom_heading', 'heading_mode', 'logo_path', 'logo_size', 'show_company_name', 'subheading'])
assert.deepEqual(Object.keys(saveContract.contact).sort(), ['address_override', 'email', 'phone_override', 'show_address', 'show_email', 'show_phone', 'show_website', 'website'])
assert.deepEqual(Object.keys(saveContract.footer).sort(), ['bold', 'message'])
assert.deepEqual(Object.keys(saveContract.thermal).sort(), ['density', 'qr_alignment', 'qr_size', 'width'])
assert.deepEqual(Object.keys(saveContract.a4), ['theme'])
assert.equal(saveContract.language, 'both')
assert.equal(saveContract.after_sale_action, 'both')
assert.equal(saveContract.thermal.qr_alignment, 'center')
assert.equal(saveContract.thermal.qr_size, 'large')
assert.equal(saveContract.footer.message, 'Thank you')
assert.equal(saveContract.footer.bold, true)
assert.equal(saveContract.branding.logo_path, 'branch-id/logo.png')
assert.doesNotMatch(JSON.stringify(saveContract), /legalSeller|legal_seller|seller|compliance|identity|display_heading|print_mode|document_format|thank_you_message|refund_note|show_footer|qr_visible|qr_enabled/)
assert.equal(canonical.language, 'ar')
assert.equal(canonical.after_sale_action, 'both')
assert.equal(canonical.branding.heading_mode, 'branch')
assert.equal(canonical.branding.custom_heading, null)
assert.equal(canonical.contact.phone_override, null)
assert.equal(canonical.footer.bold, false)
assert.equal(canonical.thermal.qr_size, 'large')
assert.equal(canonical.thermal.qr_alignment, 'center')
assert.equal(canonical.a4.theme, 'classic')
assert.equal(roundTrip.afterSaleAction, 'both')
assert.equal(roundTrip.invoiceLanguage, 'ar')
assert.equal(roundTrip.presentation.footer.bold, false)
assert.equal(roundTrip.presentation.thermal.qr_alignment, 'center')
assert.equal(preservedCanonical.future_extension.sentinel, true)
for (const obsolete of ['custom_display_name', 'thank_you_message', 'refund_note', 'show_footer', 'show_thank_you', 'show_refund_note', 'header_style']) assert.equal(Object.prototype.hasOwnProperty.call(canonical, obsolete), false)
assert.doesNotMatch(JSON.stringify(canonical), /custom_display_name|thank_you_message|refund_note|show_footer|show_thank_you|show_refund_note|header_style/)
for (const action of ['receipt', 'a4', 'both']) assert.match(page, new RegExp(`value: '${action}'`))

for (const tab of ['General', 'Header & Branding', 'Contact & Footer', 'Thermal Receipt', 'A4 Themes']) assert.match(page, new RegExp(tab))
for (const marker of ['resolveInvoicePresentationSettings', 'documentFromPreviewDraft', 'setUseBranchName', 'mobilePane', 'resetChanges', 'beforeunload', 'routeGuard', '<ThermalReceipt', '<A4Document', 'A4PreviewFit', 'role="tab"', 'role="tabpanel"']) assert.match(page, new RegExp(marker.replace(/[<>]/g, '\\$&')))
for (const field of ['phone', 'email', 'website', 'address-override']) assert.match(page, new RegExp(`p\\.contact\\.show_${field === 'address-override' ? 'address' : field} && <TextField id="${field}"`))
assert.match(read('src/lib/invoices/documentViewModel.ts'), /settings\.identity\.show_company_name \? input\.registeredName/)
assert.match(read('src/components/print/ThermalReceipt.tsx'), /seller\.company\.visible/)
assert.match(read('src/components/print/A4Document.tsx'), /seller\.registeredName/)
assert.match(totals, /Math\.abs\(totals\.taxableAmount - totals\.subtotal\) > 0\.005/)
assert.match(totals, /totals\.discount > 0\.005/)
assert.match(totals, /buildTaxBreakdown/)
