import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

const root = process.cwd()
const read = path => readFileSync(join(root, path), 'utf8')
const browserPrint = read('src/lib/print/browserPrint.ts')
const receiptPrint = read('src/lib/receiptPrint.ts')
const atomicPrint = read('src/lib/atomicReceiptPrint.ts')
const detail = read('src/pages/invoices/InvoiceDetailPage.tsx')
const pos = read('src/pages/pos/POSPage.tsx')
const receiptPage = read('src/pages/print/ReceiptPrintPage.tsx')
const preview = read('src/components/print/A4PreviewFit.tsx')
const css = read('src/index.css')

assert.match(browserPrint, /function isAndroidBrowser/)
assert.match(browserPrint, /fonts\?\.ready/)
assert.match(browserPrint, /querySelectorAll\('img'\)/)
assert.match(browserPrint, /afterprint/)
assert.match(browserPrint, /15_000/)
assert.match(browserPrint, /PRINT_POPUP_BLOCKED/)
assert.match(receiptPrint, /function openBrowserReceiptPrint\(invoiceId: string\)/)
assert.match(receiptPrint, /openPrintPopup\(receiptPreviewUrl\(invoiceId, true\)\)/)
assert.match(receiptPrint, /if \(isAndroidBrowser\(\)\) \{\s*openBrowserReceiptPrint\(invoiceId\)\s*return/)
assert.match(receiptPrint, /frame\.style\.opacity = '0'/)
assert.match(receiptPrint, /contentWindow\?\.print\(\)/)
const receiptHandlerStart = pos.indexOf('async function openReceiptPrintPage()')
const receiptHandlerEnd = pos.indexOf('\n  return (', receiptHandlerStart)
const receiptHandler = pos.slice(receiptHandlerStart, receiptHandlerEnd)
const webPrintRoute = receiptHandler.indexOf('if (!isElectron())')
const electronSnapshotRoute = receiptHandler.indexOf('if (receipt.atomicSnapshot')
assert.ok(webPrintRoute >= 0 && electronSnapshotRoute > webPrintRoute, 'Web receipt routing must run before Electron/native paths')
assert.match(receiptHandler.slice(webPrintRoute, electronSnapshotRoute), /openBrowserReceiptPrint\(receipt\.invoiceId\)/)
assert.match(receiptHandler.slice(webPrintRoute, electronSnapshotRoute), /toast\.error\(t\('printing:popupBlocked'\)\)/)
assert.doesNotMatch(receiptHandler.slice(webPrintRoute, electronSnapshotRoute), /getPrinterSettings|printReceiptInHiddenFrame|setPrintErrorKey/)
assert.match(pos, /const newSaleButton = \(\s*<button type="button" onClick=\{onNewSale\}/)
assert.match(atomicPrint, /waitForPrintableAssets/)
assert.match(atomicPrint, /printCurrentDocument\(\)/)
assert.match(detail, /if \(!isElectron\(\)\) \{\s*openPrintPopup\(`\/invoices\/\$\{encodeURIComponent\(invoice\.id\)\}\?print=1`\)/)
assert.match(pos, /if \(isAndroidBrowser\(\)\) \{[\s\S]*?openPrintPopup\(`\/invoices\/\$\{encodeURIComponent\(receipt\.invoiceId\)\}\?print=1`\)/)
assert.match(receiptPage, /waitForPrintableAssets/)
assert.match(receiptPage, /printCurrentDocument\(\)/)
assert.match(preview, /data-a4-preview-canvas/)
assert.match(preview, /data-a4-preview-document/)
assert.match(preview, /Math\.min\(1, width \/ PAGE_WIDTH\)/)
assert.match(css, /\.a4-document-frame \{ width: 210mm; min-width: 210mm; max-width: none/)
assert.match(css, /\.a4-document-frame--print-only \{ position: fixed; top: 0; left: -10000px; display: block/)
assert.match(css, /@page \{ size: A4; margin: 0; \}/)
assert.match(css, /\.a4-document \{ box-sizing: border-box; width: 210mm; min-height: 297mm/)
assert.match(css, /\.a4-document--executive_green \{ width: 210mm/)
assert.match(detail, /qrImageUrl: qrDataUrl/)
assert.match(detail, /customerCredit/)
assert.match(receiptPage, /qrImageUrl: qrDataUrl/)
assert.match(detail, /preview: autoPrint, pdfMode: true/)

console.log('Android print and A4 preview regression checks passed')
